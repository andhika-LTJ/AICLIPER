export const GLOBAL_INTRO_TEMPLATES: IntroTemplateDefinition[] = TEMPLATE_SPECS.map(buildTemplateFromSpec);

export function getIntroTemplateById(id: string): IntroTemplateDefinition | undefined {
  return GLOBAL_INTRO_TEMPLATES.find((t) => t.id === id || t.slug === id);
}

export function createEditableIntroFromTemplate(
  template: IntroTemplateDefinition,
  clipContext?: { badge?: string; headline?: string; subline?: string }
): IntroTemplateDefinition {
  const cloned: IntroTemplateDefinition = structuredClone(template);
  if (clipContext) {
    for (const layer of cloned.layers) {
      if (layer.type === 'badge' && clipContext.badge) layer.text = clipContext.badge;
      if (layer.type === 'headline' && clipContext.headline) layer.text = clipContext.headline;
      if (layer.type === 'subtitle' && clipContext.subline) layer.text = clipContext.subline;
    }
  }
  return cloned;
}
