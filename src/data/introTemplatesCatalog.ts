interface TemplateSeedSpec {
  id: string;
  slug: string;
  name: string;
  category: IntroTemplateCategory;
  description: string;
  durationSec: number;
  accentColor: string;
  background: IntroBackgroundConfig;
  badgeText: string;
  headlineText: string;
  sublineText: string;
  fontFamily: 'modern_sans' | 'condensed_viral' | 'editorial_serif' | 'studio_mono';
  enableTextBox: boolean;
  boxBgColor?: string;
  boxBorderColor?: string;
  boxRadiusPx?: number;
  headlineY: number;
  align: 'left' | 'center' | 'right';
  animation: IntroAnimationType;
  badgeColor?: string;
  headlineColor?: string;
  accentShape?: 'bar' | 'frame' | 'pill_line' | 'none';
  sfx?: IntroAudioConfig['sfxType'];
}

function buildTemplateFromSpec(spec: TemplateSeedSpec): IntroTemplateDefinition {
  const layers: IntroElementLayer[] = [];

  if (spec.accentShape && spec.accentShape !== 'none') {
    layers.push({
      id: `${spec.id}-shape`,
      type: 'shape',
      name: 'Aksen Visual',
      text: '',
      visible: true,
      x: spec.align === 'left' ? 12 : 50,
      y: Math.max(18, spec.headlineY - 12),
      widthPct: spec.accentShape === 'frame' ? 84 : 26,
      heightPct: spec.accentShape === 'frame' ? 38 : 1.2,
      fontFamily: spec.fontFamily,
      fontSizePx: 24,
      fontWeight: 700,
      textColor: spec.accentColor,
      letterSpacingPx: 0,
      lineHeight: 1.1,
      textAlign: spec.align,
      opacity: 0.92,
      rotationDeg: 0,
      shadowEnabled: false,
      shadowColor: '#000000',
      outlineEnabled: false,
      outlineColor: '#000000',
      outlineWidthPx: 0,
      textBox: {
        enabled: true,
        backgroundColor: spec.accentShape === 'frame' ? 'transparent' : spec.accentColor,
        opacity: spec.accentShape === 'frame' ? 0.2 : 0.95,
        paddingX: 0,
        paddingY: 0,
        borderRadiusPx: spec.accentShape === 'pill_line' ? 99 : 4,
        borderWidthPx: spec.accentShape === 'frame' ? 3 : 0,
        borderColor: spec.accentColor,
        shadowEnabled: false,
      },
      animation: {
        type: 'zoom_in',
        durationSec: Math.min(0.45, spec.durationSec * 0.35),
        delaySec: 0,
        direction: 'center',
        easing: 'ease_out',
        intensity: 0.7,
      },
    });
  }

  layers.push({
    id: `${spec.id}-badge`,
    type: 'badge',
    name: 'Label Kategori',
    text: spec.badgeText,
    visible: true,
    x: spec.align === 'left' ? 10 : 50,
    y: Math.max(20, spec.headlineY - 16),
    widthPct: 76,
    heightPct: 6,
    fontFamily: spec.fontFamily,
    fontSizePx: 28,
    fontWeight: 800,
    textColor: spec.badgeColor || spec.accentColor,
    letterSpacingPx: 3,
    lineHeight: 1.15,
    textAlign: spec.align,
    opacity: 1,
    rotationDeg: 0,
    shadowEnabled: true,
    shadowColor: '#000000',
    outlineEnabled: false,
    outlineColor: '#000000',
    outlineWidthPx: 0,
    textBox: {
      enabled: spec.category === 'Breaking News' || spec.category === 'Sports' || spec.category === 'Top 3/Listicle',
      backgroundColor: spec.accentColor,
      opacity: 0.95,
      paddingX: 16,
      paddingY: 6,
      borderRadiusPx: 6,
      borderWidthPx: 0,
      borderColor: spec.accentColor,
      shadowEnabled: false,
    },
    animation: {
      type: 'slide_down',
      durationSec: Math.min(0.4, spec.durationSec * 0.3),
      delaySec: 0.05,
      direction: 'down',
      easing: 'ease_out',
      intensity: 0.75,
    },
  });

  layers.push({
    id: `${spec.id}-headline`,
    type: 'headline',
    name: 'Judul Utama Hook',
    text: spec.headlineText,
    visible: true,
    x: spec.align === 'left' ? 10 : 50,
    y: spec.headlineY,
    widthPct: 84,
    heightPct: 20,
    fontFamily: spec.fontFamily,
    fontSizePx: spec.category === 'Bold Typography' || spec.category === 'Viral Hook' ? 76 : 64,
    fontWeight: 900,
    textColor: spec.headlineColor || '#FFFFFF',
    letterSpacingPx: spec.fontFamily === 'condensed_viral' ? 1.5 : 0.4,
    lineHeight: 1.12,
    textAlign: spec.align,
    opacity: 1,
    rotationDeg: 0,
    shadowEnabled: true,
    shadowColor: '#000000',
    outlineEnabled: !spec.enableTextBox,
    outlineColor: '#09090B',
    outlineWidthPx: spec.enableTextBox ? 0 : 4,
    textBox: {
      enabled: spec.enableTextBox,
      backgroundColor: spec.boxBgColor || '#09090B',
      opacity: 0.84,
      paddingX: 28,
      paddingY: 20,
      borderRadiusPx: spec.boxRadiusPx ?? 16,
      borderWidthPx: spec.boxBorderColor ? 3 : 0,
      borderColor: spec.boxBorderColor || spec.accentColor,
      shadowEnabled: true,
    },
    animation: {
      type: spec.animation,
      durationSec: Math.min(0.55, spec.durationSec * 0.4),
      delaySec: 0.1,
      direction: 'up',
      easing: 'spring',
      intensity: 0.85,
    },
  });

  layers.push({
    id: `${spec.id}-subline`,
    type: 'subtitle',
    name: 'Subjudul / Konteks',
    text: spec.sublineText,
    visible: true,
    x: spec.align === 'left' ? 10 : 50,
    y: Math.min(80, spec.headlineY + 18),
    widthPct: 78,
    heightPct: 10,
    fontFamily: 'modern_sans',
    fontSizePx: 30,
    fontWeight: 600,
    textColor: '#E2E8F0',
    letterSpacingPx: 0.2,
    lineHeight: 1.3,
    textAlign: spec.align,
    opacity: 0.94,
    rotationDeg: 0,
    shadowEnabled: true,
    shadowColor: '#000000',
    outlineEnabled: false,
    outlineColor: '#000000',
    outlineWidthPx: 0,
    textBox: {
      enabled: false,
      backgroundColor: '#0F172A',
      opacity: 0.72,
      paddingX: 16,
      paddingY: 10,
      borderRadiusPx: 10,
      borderWidthPx: 0,
      borderColor: '#334155',
      shadowEnabled: false,
    },
    animation: {
      type: 'fade_in',
      durationSec: Math.min(0.45, spec.durationSec * 0.35),
      delaySec: 0.22,
      direction: 'up',
      easing: 'ease_out',
      intensity: 0.6,
    },
  });

  return {
    id: spec.id,
    slug: spec.slug,
    name: spec.name,
    category: spec.category,
    description: spec.description,
    isGlobal: true,
    durationSec: spec.durationSec,
    safeAreaGuides: true,
    snapToCenter: true,
    background: spec.background,
    audio: {
      ...DEFAULT_INTRO_AUDIO,
      enabled: Boolean(spec.sfx),
      sfxType: spec.sfx || 'whoosh',
    },
    layers,
  };
}

