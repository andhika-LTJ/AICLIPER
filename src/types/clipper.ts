export type SocialPlatform =
  | 'youtube_shorts'
  | 'tiktok'
  | 'instagram_reels'
  | 'x_twitter'
  | 'linkedin';

export type ClipStatus =
  | 'draft'
  | 'queued'
  | 'published_auto'
  | 'published_manual'
  | 'failed';

export interface CaptionCue {
  offsetSec: number;
  durationSec: number;
  text: string;
}

export interface PlatformCopy {
  title: string;
  caption: string;
  hashtags: string[];
}

export type ClipRenderLayout =
  | 'full_16_9_focus'
  | 'shorts_studio_focus'
  | 'shorts_full_bleed'
  | 'vertical_9_16'
  | 'landscape_16_9';

export type ClipRenderQuality = '1080p' | '4k';

export type EmotionType = 'funny' | 'shock' | 'hype' | 'dramatic' | 'warm' | 'insight';

export type EmotionSfxStyle =
  | 'pop_spark'
  | 'vine_boom'
  | 'whoosh_riser'
  | 'chime_insight'
  | 'chuckle_pop'
  | 'heartbeat_hit';

export interface EmotionMoment {
  timeSec: number;
  durationSec: number;
  emotion: EmotionType;
  badgeText: string;
  sfxStyle: EmotionSfxStyle;
  intensity: number;
}

export interface PodcastClip {
  id: string;
  episodeId: string;
  orderIndex: number;
  title: string;
  hookLine: string;
  startSec: number;
  endSec: number;
  ringkasanTeks: string;
  poinKunci: string[];
  transcriptExcerpt: string;
  captionCues: CaptionCue[];
  priorityLabel: 'Sorotan Utama' | 'Klip Pendukung';
  viralScore?: number;
  viralReason?: string;
  status: ClipStatus;
  publishedPlatforms: SocialPlatform[];
  lastPublishedAt?: string;
  youtubeVideoId?: string;
  youtubeWatchUrl?: string;
  renderedClipUrl?: string;
  renderedLayout?: ClipRenderLayout;
  renderedQuality?: ClipRenderQuality;
  renderedSourceWidth?: number;
  renderedSourceHeight?: number;
  renderedSourceType?: 'uploaded_video' | 'direct_video_url' | 'youtube_stream' | 'third_party_downloader';
  renderedFileSizeBytes?: number;
  subtitleAccuracySource?: 'audio_transcribed' | 'youtube_captions' | 'ai_estimated';
  autoGeneratedTitle?: string;
  autoGeneratedCaption?: string;
  speakerFocusSummary?: string;
  emotionSummary?: string;
  emotionMoments?: EmotionMoment[];
  emotionEffectsEnabled?: boolean;
  platformCopies: Record<SocialPlatform, PlatformCopy>;
}

export interface PodcastEpisode {
  id: string;
  videoId: string;
  sourceUrl: string;
  title: string;
  channelName: string;
  thumbnailUrl: string;
  fallbackImageUrl: string;
  durationSec: number;
  transcriptSource:
    | 'youtube_captions'
    | 'audio_sampled'
    | 'metadata_and_search'
    | 'manual_transcript'
    | 'curated_sample';
  episodeSummary: string;
  keyTopics: string[];
  hasUploadedSourceVideo?: boolean;
  directVideoUrl?: string;
  createdAt: string;
}

export interface DistributionLog {
  id: string;
  clipId: string;
  clipTitle: string;
  episodeTitle: string;
  mode: 'auto' | 'manual';
  platforms: SocialPlatform[];
  webhookDelivered: boolean;
  webhookStatusCode?: number;
  status: 'success' | 'partial' | 'failed';
  message: string;
  timestamp: string;
}

export interface BotAutomationConfig {
  autoPostOnAnalyze: boolean;
  defaultPlatforms: SocialPlatform[];
  minClipSec: number;
  maxClipSec: number;
  targetClipCount: number;
  youtubeDefaultVisibility: 'public' | 'unlisted' | 'private';
  webhookUrl: string;
  webhookSecretHeader: string;
  autoAddHashtagShorts: boolean;
  enableUltraHdRender: boolean;
  enableAiEmotionEffects: boolean;
  defaultRenderQuality: ClipRenderQuality;
  defaultRenderLayout: 'shorts_full_bleed' | 'shorts_studio_focus' | 'full_16_9_focus';
}

export interface StudioStoreState {
  episodes: PodcastEpisode[];
  clips: PodcastClip[];
  distributionLogs: DistributionLog[];
  automation: BotAutomationConfig;
}
